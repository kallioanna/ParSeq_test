#!/bin/bash

# Проверка соответствия идентификаторов хромосом между BED-файлом
# целевой панели и GFF-файлом референсной аннотации.

# Проверка количества аргументов командной строки.
if [ "$#" -ne 2 ]; then
    echo "Использование:"
    echo "  $0 <panel.bed> <reference.gff>"
    exit 1
fi

# Определение входных файлов.
BED_FILE="$1"
GFF_FILE="$2"

# Проверка существования BED-файла.
if [ ! -f "$BED_FILE" ]; then
    echo "ОШИБКА: BED-файл не найден: $BED_FILE"
    exit 1
fi

# Проверка существования GFF-файла.
if [ ! -f "$GFF_FILE" ]; then
    echo "ОШИБКА: GFF-файл не найден: $GFF_FILE"
    exit 1
fi

# Формирование списка уникальных идентификаторов хромосом,
# присутствующих в BED-файле панели.
grep -vE '^(track|#)' "$BED_FILE" |
    cut -f1 |
    sort -u > panel.chromosomes.txt

# Формирование списка уникальных идентификаторов последовательностей,
# присутствующих в GFF-файле референсной аннотации.
grep -v '^#' "$GFF_FILE" |
    cut -f1 |
    sort -u > reference.chromosomes.txt

# Проверка наличия хромосом из BED-файла в GFF-файле.
# Команда comm -23 возвращает элементы первого списка,
# отсутствующие во втором списке.
MISSING_CHROMOSOMES=$(comm -23 \
    panel.chromosomes.txt \
    reference.chromosomes.txt)

# Анализ результата проверки.
if [ -n "$MISSING_CHROMOSOMES" ]; then

    echo "Оib,rf: обнаружены хромосомы, присутствующие в BED-файле,"
    echo "но отсутствующие в GFF-файле референсной аннотации:"
    echo
    echo "$MISSING_CHROMOSOMES"
    echo
    echo "Проверка соответствия хромосом не пройдена."
    exit 1

else

    echo "Проверка соответствия хромосом успешно завершена."
    echo "Все хромосомы, представленные в BED-файле панели,"
    echo "присутствуют в GFF-файле референсной аннотации."

fi
